def build_bundle(args: argparse.Namespace) -> int:
    repo: Path = args.repo
    out: Path = args.out
    pin = load_pin_text(pin_file(repo).read_text(encoding="utf-8"))
    target = pick_target(pin, args.os, args.arch)
    if target.kind != archive_kind_for(args.os):
        raise BundleError(f"pin target kind {target.kind} inconsistent with os {args.os}")
    _log(f"pg pin: {pin.source_repo} @ {pin.release_tag} -> {', '.join(sorted(pin.targets))}")

    stage = out / ".bundle-stage" / f"{args.os}-{args.arch}"
    work = out / ".bundle-work" / f"{args.os}-{args.arch}"
    if args.skip_pg and not (stage / "pg").is_dir():
        raise BundleError(f"--skip-pg requires an existing staged pg/ tree: {stage / 'pg'}")
    if not (args.skip_pyinstaller or args.skip_pg):
        shutil.rmtree(stage, ignore_errors=True)
    stage.mkdir(parents=True, exist_ok=True)
    work.mkdir(parents=True, exist_ok=True)

    app_stubbed = False
    if args.skip_pyinstaller:
        if (stage / "app").is_dir():
            _log(f"stage app: reusing staged tree {stage / 'app'}")
        else:
            _log("stage app: fabricated layout stub (--skip-pyinstaller, no staged app/)")
            _fabricate_stub_app(stage / "app", args.os)
            app_stubbed = True
    else:
        _log("stage app: PyInstaller onedir `hr`")
        shutil.rmtree(stage / "app", ignore_errors=True)
        run_pyinstaller(repo, work, stage / "app")

    if args.skip_pg:
        if not (stage / "pg").is_dir():
            raise BundleError("--skip-pg but stage/pg does not exist")
    else:
        _log(f"stage pg: theseus {pin.release_tag} ({target.triple})")
        cached = fetch_pg(pin, target, args.pg_cache)
        with tempfile.TemporaryDirectory(prefix="aihr-pg-") as tmp:
            root = extract_pg(cached, target.kind, Path(tmp) / "x")
            shutil.rmtree(stage / "pg", ignore_errors=True)
            normalize_pg(root, stage / "pg", args.os)
        if args.os == "linux":
            for member in stage_pg_libs(repo, stage / "pg", args.pg_cache.parent / "libs"):
                _log(f"  vendored {member}")

    _log("stage share: repo templates -> share/aihr/")
    shutil.rmtree(stage / "share", ignore_errors=True)
    build_share(repo, stage / "share")

    archive = out / bundle_archive_name(args.version, args.os, args.arch)
    _log(f"archiving -> {archive}")
    create_archive(stage, archive, archive_kind_for(args.os))
    sidecar = write_sidecar(archive)
    _log(f"sidecar -> {sidecar}")

    verify_archive_checksum(archive)
    problems = check_bundle_members(list_members(archive), args.os)
    if problems:
        raise BundleError(f"assembled archive violates D-layout contract: {problems}")
    if args.skip_pyinstaller:
        note = "fabricated stub" if app_stubbed else "reused staged tree"
        _log(f"smoke skipped (--skip-pyinstaller, {note}): layout-test bundle, NOT release-grade")
    else:
        smoke_app(stage / "app", args.os)
    _log(f"bundle ready: {archive} ({archive.stat().st_size} bytes)")
    return 0


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build an AIHR turnkey bundle (app + vendored pg + templates)."
    )
    mode = parser.add_argument_group("target selection")
    mode.add_argument("--os", choices=OS_NAMES, help="target OS")
    mode.add_argument("--arch", choices=ARCH_NAMES, default="x86_64", help="target CPU arch")
    mode.add_argument("--version", help="bundle version, e.g. 0.4.0")
    mode.add_argument("--out", type=Path, default=Path("dist"), help="output dir (default: dist/)")
    mode.add_argument("--repo", type=Path, default=default_repo_root(), help="repo root")
    mode.add_argument(
        "--pg-cache",
        type=Path,
        default=default_pg_cache_dir(),
        help="theseus asset cache dir (sha256-checked before reuse)",
    )
    mode.add_argument(
        "--skip-pyinstaller",
        action="store_true",
        help="do not freeze app/: reuse stage/app if present, else fabricate a layout stub "
        "(core-only bundle for selftest; NEVER release-grade)",
    )
    mode.add_argument("--skip-pg", action="store_true", help="reuse staged pg/ tree")
    ops = parser.add_argument_group("archive operations (no build)")
    ops.add_argument("--list", action="store_true", help="print archive members and exit")
    ops.add_argument(
        "--verify", action="store_true", help="verify archive checksum + layout and exit"
    )
    ops.add_argument(
        "--archive", type=Path, help="archive for --list/--verify (default: newest in --out)"
    )
    parser.add_argument(
        "--self-test", action="store_true", help="run pure-logic tests offline and exit"
    )
    args = parser.parse_args(argv)

    if args.self_test:
        return args
    if args.list or args.verify:
        if args.archive is None:
            args.archive = _newest_archive(args.out, args.os, args.arch)
        return args
    if not args.os or not args.version:
        parser.error(
            "--os and --version are required for a build (or use --list/--verify/--self-test)"
        )
    return args


def _newest_archive(out: Path, os_name: str | None, arch: str | None) -> Path:
    pattern = f"aihr-*-{os_name or '*'}-{arch or '*'}.*"
    candidates = sorted(out.glob(pattern), key=lambda p: p.stat().st_mtime, reverse=True)
    if not candidates:
        raise BundleError(f"no archive matching {pattern} in {out}")
    return candidates[0]


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        if args.self_test:
            from scripts.bundle_selftest import run_self_test

            return run_self_test()
        if args.list:
            return handle_list(args.archive)
        if args.verify:
            return handle_verify(args.archive)
        return build_bundle(args)
    except BundleError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as exc:
        print(f"error: subprocess failed ({exc.cmd[0]} exit {exc.returncode})", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
