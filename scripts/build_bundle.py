def build_share(repo: Path, dest_share: Path) -> None:
    """Copy the repo templates into D-layout share/aihr/ (secret-free by contract)."""
    template = repo / "hr.toml.example"
    configs_dir = repo / "configs"
    if not template.is_file() or not configs_dir.is_dir():
        raise BundleError(f"repo templates missing: {template} / {configs_dir}")
    target = dest_share / "aihr"
    (target / "configs").mkdir(parents=True, exist_ok=True)
    shutil.copy2(template, target / "hr.toml.example")
    shipped = 0
    for yaml_file in sorted(configs_dir.glob("*.yaml")):
        if yaml_file.name.endswith(".local.yaml"):  # gitignored local overlays: never ship
            continue
        shutil.copy2(yaml_file, target / "configs" / yaml_file.name)
        shipped += 1
    _log(f"share templates: hr.toml.example + {shipped} configs/*.yaml")


def create_archive(stage: Path, archive: Path, kind: str) -> None:
    if kind == "tar.gz":
        with tarfile.open(archive, "w:gz", compresslevel=9) as tf:
            for child in sorted(stage.iterdir()):
                tf.add(child, arcname=child.name)  # preserves exec bits from staging
    else:
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
            for path in sorted(stage.rglob("*")):
                if path.is_file():
                    zf.write(path, path.relative_to(stage).as_posix())


def write_sidecar(archive: Path) -> Path:
    sidecar = archive.with_name(archive.name + ".sha256")
    sidecar.write_text(sidecar_text(archive.name, sha256_file(archive)), encoding="ascii")
    return sidecar


