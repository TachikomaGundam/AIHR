#: Modules that PyInstaller's static graph may miss behind optional/lazy imports.
HIDDEN_IMPORTS: Final[tuple[str, ...]] = (
    "psycopg2",
    "psycopg2.extensions",
    "typer",
    "rich",
    "yaml",
)

_ENTRY_STUB = '''"""Frozen console entry point for the AIHR bundle (generated by build_bundle.py)."""

from hr.cli import app

if __name__ == "__main__":
    app()
'''


def _log(msg: str) -> None:
    print(f"[bundle] {msg}", flush=True)


# --------------------------------------------------------------------------
# (b) vendored PostgreSQL
# --------------------------------------------------------------------------


def fetch_pg(pin: PgPin, target: PgTarget, cache_dir: Path) -> Path:
    """Return the cached theseus asset path, downloading + sha256-verifying on miss.

    A cached file with the wrong digest is treated as a poisoned cache entry:
    it is re-downloaded once, and a second mismatch is a hard error.
    """
    cache_dir.mkdir(parents=True, exist_ok=True)
    dest = cache_dir / target.asset
    for attempt in (1, 2):
        if dest.is_file():
            actual = sha256_file(dest)
            if actual == target.sha256:
                _log(f"pg cache hit (sha256 verified): {dest.name}")
                return dest
            if attempt == 1:
                _log(f"WARNING: cache digest mismatch for {dest.name}; re-downloading")
                dest.unlink()
            else:
                raise BundleError(
                    f"re-downloaded asset still has wrong sha256 for {target.asset}: "
                    f"{actual} != {target.sha256}"
                )
        url = download_url(pin, target)
        _log(f"downloading {url}")
        request = urllib.request.Request(url, headers={"User-Agent": "aihr-build-bundle"})
        tmp = dest.with_name(f"{target.asset}.part{attempt}")
        with urllib.request.urlopen(request, timeout=300) as resp, tmp.open("wb") as fh:
            shutil.copyfileobj(resp, fh)
        actual = sha256_file(tmp)
        if actual != target.sha256:
            tmp.unlink(missing_ok=True)
            if attempt == 1:
                continue
            raise BundleError(
                f"downloaded asset has wrong sha256 for {target.asset}: "
                f"{actual} != {target.sha256}"
            )
        tmp.replace(dest)
        _log(f"pg cached: {dest} ({dest.stat().st_size} bytes)")
        return dest
    raise BundleError(f"unreachable: fetch loop for {target.asset} exited without result")


def extract_pg(archive: Path, kind: str, dest: Path) -> Path:
    """Extract a theseus tar.gz/zip into ``dest`` and return the normalized pg root."""
    dest.mkdir(parents=True, exist_ok=True)
    if kind == "tar.gz":
        with tarfile.open(archive, "r:gz") as tf:
            tf.extractall(dest, filter="data")
    else:
        with zipfile.ZipFile(archive) as zf:
            zf.extractall(dest)
    return pick_pg_root(dest)


# --------------------------------------------------------------------------
# (a2) linux system-library closure: pinned .deb -> pg/lib/
# --------------------------------------------------------------------------


def fetch_deb(entry: DebPin, cache_dir: Path) -> Path:
    """Return the cached .deb, downloading + sha256-verifying on miss.

    Same poisoned-cache contract as :func:`fetch_pg`: re-download once, hard
    error on a second mismatch.
    """
    cache_dir.mkdir(parents=True, exist_ok=True)
    dest = cache_dir / entry.asset
    for attempt in (1, 2):
        if dest.is_file():
            actual = sha256_file(dest)
            if actual == entry.sha256:
                _log(f"deb cache hit (sha256 verified): {dest.name}")
                return dest
            if attempt == 1:
                _log(f"WARNING: cache digest mismatch for {dest.name}; re-downloading")
                dest.unlink()
            else:
                raise BundleError(
                    f"re-downloaded .deb still has wrong sha256 for {entry.asset}: "
                    f"{actual} != {entry.sha256}"
                )
        _log(f"downloading {entry.url}")
        request = urllib.request.Request(entry.url, headers={"User-Agent": "aihr-build-bundle"})
        tmp = dest.with_name(f"{entry.asset}.part{attempt}")
        with urllib.request.urlopen(request, timeout=300) as resp, tmp.open("wb") as fh:
            shutil.copyfileobj(resp, fh)
        actual = sha256_file(tmp)
        if actual != entry.sha256:
            tmp.unlink(missing_ok=True)
            raise BundleError(f"downloaded .deb sha256 mismatch for {entry.asset}")
        tmp.rename(dest)
        return dest
    raise BundleError("unreachable: fetch loop returned no path")


def stage_pg_libs(repo: Path, pg_dest: Path, cache_dir: Path) -> list[str]:
    """Vendor the pinned library closure into ``pg_dest/lib`` (linux targets).

    Requires GNU ``ar`` + zstd-capable ``tar`` on PATH (both present on the
    CI ubuntu runners). Returns the staged member names for logging.
    """
    entries = parse_libs_pin(libs_pin_file(repo).read_text(encoding="utf-8"))
    lib_dir = pg_dest / "lib"
    lib_dir.mkdir(parents=True, exist_ok=True)
    staged: list[str] = []
    for entry in entries:
        deb = fetch_deb(entry, cache_dir)
        with tempfile.TemporaryDirectory(prefix="aihr-deb-") as tmp:
            work = Path(tmp)
            subprocess.run(["ar", "x", str(deb)], check=True, cwd=work)
            data = next(iter(sorted(work.glob("data.tar.*"))), None)
            if data is None:
                raise BundleError(f"{deb.name} contains no data.tar.* member")
            subprocess.run(["tar", "-xf", str(data.name)], check=True, cwd=work)
            for spec in entry.files:
                src = work / spec.member
                if not src.is_file():
                    raise BundleError(f"{deb.name} lacks member {spec.member}")
                shutil.copy2(src, lib_dir / spec.dest)
                link = lib_dir / spec.symlink
                if link.is_symlink() or link.exists():
                    link.unlink()
                link.symlink_to(spec.dest)
                staged.append(f"pg/lib/{spec.symlink} -> {spec.dest}")
    (lib_dir / "NOTICE").write_text(PG_LIBS_NOTICE, encoding="utf-8")
    staged.append("pg/lib/NOTICE")
    return staged


