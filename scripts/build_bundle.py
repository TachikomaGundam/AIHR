def run_pyinstaller(repo: Path, work: Path, app_dest: Path) -> Path:
    """Freeze the `hr` CLI into an onedir tree at ``app_dest``; return it.

    The post-archive ``smoke_app`` run is the build gate (frozen ``hr --help``).
    """
    if find_spec("PyInstaller") is None:
        raise BundleError(
            "PyInstaller not importable — run this script via "
            "`uv run --with pyinstaller python scripts/build_bundle.py ...`"
        )
    pyi = work / "pyinstaller"
    entry = pyi / "hr_entry.py"
    entry.parent.mkdir(parents=True, exist_ok=True)
    entry.write_text(_ENTRY_STUB, encoding="utf-8")
    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--console",
        "--name",
        "hr",
        "--paths",
        str(repo),
        "--copy-metadata",
        "aihr",
        *(f"--hidden-import={m}" for m in HIDDEN_IMPORTS),
        "--distpath",
        str(pyi / "dist"),
        "--workpath",
        str(pyi / "build"),
        "--specpath",
        str(pyi),
        str(entry),
    ]
    _log(f"pyinstaller: {' '.join(cmd[:10])} ...")
    subprocess.run(cmd, check=True, cwd=repo)
    built = pyi / "dist" / "hr"
    if not built.is_dir():
        raise BundleError(f"PyInstaller did not produce onedir tree at {built}")
    shutil.copytree(built, app_dest, dirs_exist_ok=True, symlinks=True)
    return app_dest


def smoke_app(app_dir: Path, os_name: str) -> None:
    """Run ``app/hr --help`` from the frozen tree — the build smoke gate."""
    exe = app_dir / f"hr{exe_suffix(os_name)}"
    if not exe.is_file():
        raise BundleError(f"bundle app executable missing: {exe}")
    proc = subprocess.run([str(exe), "--help"], capture_output=True, text=True, timeout=120)
    if proc.returncode != 0:
        raise BundleError(
            f"frozen `hr --help` exited {proc.returncode}\n"
            f"stdout: {proc.stdout[-2000:]}\nstderr: {proc.stderr[-2000:]}"
        )
    _log("smoke ok: frozen `hr --help` exits 0")


def _fabricate_stub_app(app_dir: Path, os_name: str) -> None:
    app_dir.mkdir(parents=True, exist_ok=True)
    internal = app_dir / "_internal"
    internal.mkdir(exist_ok=True)
    (internal / "base_library.zip").write_bytes(b"aihr-stub")
    entry = app_dir / f"hr{exe_suffix(os_name)}"
    entry.write_text("#!/bin/sh\necho 'hr stub: layout-test bundle, not release-grade'\n", encoding="utf-8")
    entry.chmod(0o755)


