def list_members(archive: Path) -> list[str]:
    if archive.name.endswith(".tar.gz"):
        with tarfile.open(archive, "r:gz") as tf:
            return [m.name for m in tf.getmembers()]
    with zipfile.ZipFile(archive) as zf:
        return zf.namelist()


def os_from_archive_name(name: str) -> str:
    for os_name in OS_NAMES:
        if f"-{os_name}-" in name:
            return os_name
    raise BundleError(f"cannot infer target OS from archive name: {name}")


def handle_verify(archive: Path) -> int:
    os_name = os_from_archive_name(archive.name)
    expected, actual = verify_archive_checksum(archive)
    problems = check_bundle_members(list_members(archive), os_name)
    if problems:
        for p in problems:
            print(f"  LAYOUT PROBLEM: {p}")
        return 1
    print(f"OK {archive.name}\n  sha256 verified: {actual} (sidecar match: {expected})")
    for req in required_bundle_members(os_name):
        print(f"  present: {req}")
    return 0


def handle_list(archive: Path) -> int:
    for member in list_members(archive):
        print(member)
    return 0


