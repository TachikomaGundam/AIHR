"""Build a self-contained AIHR turnkey bundle (Item 11 packaging).

Run from the repo root::

    uv run --with pyinstaller python scripts/build_bundle.py \\
        --os linux --arch x86_64 --version 0.4.0 --out dist/

Produces ``dist/aihr-<version>-<os>-<arch>.tar.gz`` (or ``.zip`` on windows)
plus a ``.sha256`` sidecar. Staging layout (no top-level prefix in the
archive) and pinning rules: see ``scripts/bundle_core.py``.

Network is used for exactly one thing: downloading the pinned theseus-rs
PostgreSQL asset (cached under --pg-cache, sha256-verified before reuse).
``--self-test`` runs the pure logic offline; ``--list`` / ``--verify``
inspect a produced archive.
"""

